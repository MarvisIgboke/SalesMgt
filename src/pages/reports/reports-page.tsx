import { useState, type ReactNode } from 'react'
import { useMutation, useQuery } from '@tanstack/react-query'
import {
  BarChart3,
  Download,
  FileSpreadsheet,
  FileText,
  Package,
  Play,
  Wallet,
} from 'lucide-react'
import {
  reportsApi,
  type ExportFormat,
  type ReportDataset,
  type ReportParams,
  type ReportType,
} from '@/lib/api/endpoints/reports'
import { useAppStore } from '@/stores/app'
import { PageHeader } from '@/components/common/page-header'
import { LoadingState } from '@/components/common/loading-state'
import { ErrorState } from '@/components/common/error-state'
import { EmptyState } from '@/components/common/empty-state'
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from '@/components/ui/table'
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from '@/components/ui/card'
import { Button } from '@/components/ui/button'
import { Input } from '@/components/ui/input'
import { Badge } from '@/components/ui/badge'
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from '@/components/ui/select'
import { toast } from '@/components/ui/sonner'
import { ApiError } from '@/lib/api/errors'
import { cn, formatCurrency, formatDate } from '@/lib/utils'

interface AppliedReport {
  report_type: ReportType | ''
  from?: string
  to?: string
  branch_id?: number
  group_by?: string
}

interface ReportGroup {
  label: string
  icon: ReactNode
  reports: ReportType[]
}

const REPORT_GROUPS: ReportGroup[] = [
  {
    label: 'Sales',
    icon: <BarChart3 className="h-4 w-4" />,
    reports: ['sales', 'revenue', 'profit', 'cash-variance', 'reconciliation'],
  },
  {
    label: 'Inventory',
    icon: <Package className="h-4 w-4" />,
    reports: [
      'inventory-valuation',
      'inventory-movement',
      'low-stock',
      'expired',
      'expiring',
      'damaged',
      'transfers',
    ],
  },
  {
    label: 'Finance',
    icon: <Wallet className="h-4 w-4" />,
    reports: ['expenses', 'receivables', 'payables'],
  },
]

const CURRENCY_HINTS = ['amount', 'total', 'value', 'sales', 'revenue', 'cost', 'profit']

function reportTitle(type: ReportType): string {
  return type
    .split('-')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ')
}

function toParams(applied: AppliedReport): ReportParams {
  return {
    report_type: applied.report_type || undefined,
    from: applied.from,
    to: applied.to,
    branch_id: applied.branch_id,
    group_by: applied.group_by,
  }
}

function formatSummaryValue(key: string, value: number | string): string {
  const lower = key.toLowerCase()
  const isCurrency = CURRENCY_HINTS.some((hint) => lower.includes(hint))
  if (isCurrency && typeof value === 'number') return formatCurrency(value)
  return String(value)
}

function renderCell(value: string | number | null | undefined): string {
  if (value === null || value === undefined || value === '') return '—'
  return String(value)
}

export function ReportsPage() {
  const branches = useAppStore((s) => s.branches)
  const [reportType, setReportType] = useState<ReportType | ''>('')
  const [from, setFrom] = useState('')
  const [to, setTo] = useState('')
  const [branchId, setBranchId] = useState('')
  const [groupBy, setGroupBy] = useState('day')
  const [applied, setApplied] = useState<AppliedReport>({ report_type: '' })

  const { data, isLoading, isError, error, refetch } = useQuery({
    queryKey: ['reports', applied],
    queryFn: () => reportsApi.get(toParams(applied)),
    enabled: !!applied.report_type,
    placeholderData: (prev) => prev,
  })

  const exportReport = useMutation({
    mutationFn: (format: ExportFormat) => reportsApi.export(format, toParams(applied)),
    onSuccess: (res) => {
      toast.success(`Export ready: ${res.data.filename || 'file'}`)
    },
    onError: (err) => {
      toast.error('Export failed', {
        description: err instanceof ApiError ? err.message : undefined,
      })
    },
  })

  const dataset: ReportDataset | undefined = data?.data
  const rows = dataset
    ? (dataset.rows as unknown as Array<Record<string, string | number>>)
    : []

  const runReport = () => {
    setApplied({
      report_type: reportType,
      from: from || undefined,
      to: to || undefined,
      branch_id: branchId ? Number(branchId) : undefined,
      group_by: groupBy || undefined,
    })
  }

  return (
    <div className="animate-fade-in">
      <PageHeader
        title="Reports"
        description="Run authoritative datasets generated by the backend and export them as PDF, Excel or CSV."
      />

      <div className="grid gap-6 lg:grid-cols-[280px_1fr]">
        <aside className="space-y-6">
          {REPORT_GROUPS.map((group) => (
            <div key={group.label} className="space-y-2">
              <div className="flex items-center gap-2 text-[11px] font-semibold uppercase tracking-widest text-muted-foreground">
                {group.icon}
                {group.label}
              </div>
              <div className="flex flex-col gap-1">
                {group.reports.map((type) => (
                  <Button
                    key={type}
                    type="button"
                    variant={reportType === type ? 'default' : 'outline'}
                    size="sm"
                    className={cn('w-full justify-start', reportType === type && 'shadow-sm')}
                    onClick={() => setReportType(type)}
                  >
                    {reportTitle(type)}
                  </Button>
                ))}
              </div>
            </div>
          ))}
        </aside>

        <section className="min-w-0 space-y-6">
          {!reportType ? (
            <EmptyState
              title="Select a report to begin"
              description="Choose a report from the list, set your filters, then run it."
              icon={<BarChart3 className="h-6 w-6" />}
            />
          ) : (
            <>
              <Card>
                <CardContent className="grid gap-4 p-5 sm:grid-cols-2 sm:p-6 xl:grid-cols-5">
                  <div className="grid gap-2">
                    <span className="text-xs font-medium text-muted-foreground">From</span>
                    <Input
                      type="date"
                      value={from}
                      onChange={(e) => setFrom(e.target.value)}
                    />
                  </div>
                  <div className="grid gap-2">
                    <span className="text-xs font-medium text-muted-foreground">To</span>
                    <Input type="date" value={to} onChange={(e) => setTo(e.target.value)} />
                  </div>
                  <div className="grid gap-2">
                    <span className="text-xs font-medium text-muted-foreground">Branch</span>
                    <Select
                      value={branchId || 'all'}
                      onValueChange={(value) => setBranchId(value === 'all' ? '' : value)}
                    >
                      <SelectTrigger>
                        <SelectValue placeholder="All branches" />
                      </SelectTrigger>
                      <SelectContent>
                        <SelectItem value="all">All branches</SelectItem>
                        {branches.map((branch) => (
                          <SelectItem key={branch.id} value={String(branch.id)}>
                            {branch.name}
                          </SelectItem>
                        ))}
                      </SelectContent>
                    </Select>
                  </div>
                  <div className="grid gap-2">
                    <span className="text-xs font-medium text-muted-foreground">Group by</span>
                    <Select
                      value={groupBy || 'none'}
                      onValueChange={(value) => setGroupBy(value === 'none' ? '' : value)}
                    >
                      <SelectTrigger>
                        <SelectValue placeholder="Group by" />
                      </SelectTrigger>
                      <SelectContent>
                        <SelectItem value="day">Day</SelectItem>
                        <SelectItem value="week">Week</SelectItem>
                        <SelectItem value="month">Month</SelectItem>
                        <SelectItem value="quarter">Quarter</SelectItem>
                        <SelectItem value="none">None</SelectItem>
                      </SelectContent>
                    </Select>
                  </div>
                  <div className="flex items-end">
                    <Button type="button" className="w-full" onClick={runReport}>
                      <Play className="h-4 w-4" />
                      Run report
                    </Button>
                  </div>
                </CardContent>
              </Card>

              {isLoading && <LoadingState variant="table" />}

              {isError && !isLoading && (
                <ErrorState error={error} onRetry={() => refetch()} />
              )}

              {dataset && !isLoading && !isError && (
                <Card>
                  <CardHeader className="flex-col gap-3 sm:flex-row sm:items-center sm:justify-between sm:space-y-0">
                    <div>
                      <CardTitle>{dataset.title}</CardTitle>
                      <CardDescription>
                        {formatDate(dataset.period.from)} – {formatDate(dataset.period.to)}
                      </CardDescription>
                    </div>
                    <div className="flex items-center gap-2">
                      <Button
                        variant="outline"
                        size="sm"
                        loading={exportReport.isPending}
                        onClick={() => exportReport.mutate('pdf')}
                      >
                        <FileText className="h-4 w-4" />
                        PDF
                      </Button>
                      <Button
                        variant="outline"
                        size="sm"
                        loading={exportReport.isPending}
                        onClick={() => exportReport.mutate('excel')}
                      >
                        <FileSpreadsheet className="h-4 w-4" />
                        Excel
                      </Button>
                      <Button
                        variant="outline"
                        size="sm"
                        loading={exportReport.isPending}
                        onClick={() => exportReport.mutate('csv')}
                      >
                        <Download className="h-4 w-4" />
                        CSV
                      </Button>
                    </div>
                  </CardHeader>
                  <CardContent className="space-y-4">
                    {Object.keys(dataset.summary).length > 0 && (
                      <div className="flex flex-wrap gap-2">
                        {Object.entries(dataset.summary).map(([key, value]) => (
                          <Badge key={key} variant="outline">
                            {key.replace(/_/g, ' ')}: {formatSummaryValue(key, value)}
                          </Badge>
                        ))}
                      </div>
                    )}

                    {rows.length === 0 ? (
                      <EmptyState title="No data for this report" />
                    ) : (
                      <Table>
                        <TableHeader>
                          <TableRow>
                            {dataset.columns.map((column) => (
                              <TableHead key={column}>{column.replace(/_/g, ' ')}</TableHead>
                            ))}
                          </TableRow>
                        </TableHeader>
                        <TableBody>
                          {rows.map((row, index) => (
                            <TableRow key={index}>
                              {dataset.columns.map((column) => (
                                <TableCell
                                  key={column}
                                  className="tabular-nums text-muted-foreground"
                                >
                                  {renderCell(row[column])}
                                </TableCell>
                              ))}
                            </TableRow>
                          ))}
                        </TableBody>
                      </Table>
                    )}
                  </CardContent>
                </Card>
              )}
            </>
          )}
        </section>
      </div>
    </div>
  )
}
